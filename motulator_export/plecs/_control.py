# Model initialization
def _value(value: Any) -> str:
    """Value in the model initialization: an integer without the decimal point."""
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    if isinstance(value, (int, float)) and float(value).is_integer() and value < 1e15:
        return str(int(value))
    return _fmt_mask(value) if isinstance(value, float) else _fmt(value)


def assign(name: str, value: Any) -> str:
    """Assignment of the model initialization."""
    return f"{name} = {_value(value)};\n"


def init_header(variables: list[tuple[str, Any]], comment: str) -> str:
    """The comment and the variables of the system model."""
    return (
        comment + "\n"
        "%% System model\n" + "".join(assign(n, v) for n, v in variables) + "\n"
        "%% Control system ([] = None, the default)\n"
    )


def speed_ctrl_init(values: dict[str, Any]) -> str:
    """The struct speed_ctrl of the model initialization."""
    return "% Speed controller (SpeedController)\n" + "".join(
        assign(f"speed_ctrl.{n}", values[f"speed_{n}"])
        for n in ("J", "alpha_s", "alpha_i", "tau_M_max")
    )


def pwm_init(values: dict[str, Any]) -> str:
    """The struct pwm of the model initialization."""
    return (
        "% PWM: the duty-ratio error model d_err = dead_time_error(i_abc, d_abc,\n"
        "% t_d, cfg.T_s, sign) with sign = tanh(i/i_0) (np.sign if i_0 = 0), its\n"
        "% compensation, the minimum duty ratio of a switching leg, and the\n"
        "% overmodulation ('MPE' or 'MME')\n"
        + "".join(
            assign(f"pwm.{n}", values[f"pwm_{n}"])
            for n in ("t_d", "i_0", "feedforward", "d_min", "overmodulation")
        )
    )


