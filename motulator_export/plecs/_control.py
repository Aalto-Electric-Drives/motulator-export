def get_measurement(
    sig: Signals, inputs: list[Port], fields: list[tuple[str, str]], prelude: str = ""
) -> CBlock:
    """Measurements (get_measurement): the fields of meas from the inputs."""
    output = (
        prelude + f"{sig.vectors['meas'][0]} meas;\n"
        "/* Measurements, the DC-bus voltage limited to U_DC_MIN */\n"
        + "".join(f"meas.{n} = {v};\n" for n, v in fields)
        + sig.write(0, "meas", "meas")
    )
    m_fields = ", ...\n    ".join(f"'{n}', {c_to_matlab(v, inputs)}" for n, v in fields)
    mcode = MCode(
        output="% Measurements, the DC-bus voltage limited to U_DC_MIN = 1 V\n"
        f"meas = struct( ...\n    {m_fields});\n",
        outputs={"meas": sig.vector("meas")},
    )
    return CBlock(
        "get_measurement",
        inputs,
        [sig.port("meas")],
        sig.function_code(output, workspace=C_U_DC_MIN),
        ["T_s"],
        sig.sfunction("get_measurement"),
        mcode=mcode,
    )


def abc_input(name: str, port: int) -> str:
    """C code reading a three-phase input."""
    return (
        f"double {name}[3] = {{InputSignal({port}, 0), InputSignal({port}, 1),\n"
        f"    InputSignal({port}, 2)}};\n"
    )


def pcc_voltage_input(port: int) -> str:
    """C code reading the measured line-to-line PCC voltages u_ab and u_bc."""
    return (
        "/* Line-to-line PCC voltages u_ab and u_bc */\n"
        f"double u_g_line[2] = {{InputSignal({port}, 0), InputSignal({port}, 1)}};\n"
    )


# Angle-advance factor of the voltage reference, given by the controllers (k_comp)
K_COMP = 1.5


def modulate(sig: Signals, u: str, standby: bool = False) -> CBlock:
    """
    Voltage reference for the PWM (modulate): the voltage reference `u` (e.g.,
    ref.u_s) in stationary coordinates, its angle advanced by `k_comp*T_s*w_c`, and
    the angular speed of the coordinates. With `standby`, the block has the input
    `standby` of a vector control system, in which the voltage reference of a
    sensorless drive is the zero vector (VectorControlSystem.modulate).
    """
    zero_vector = (
        "/* The zero vector of a sensorless drive in standby */\n"
        "if (sensorless && InputSignal(2, 0) != 0.0) {\n"
        "    u_c_ref_ab = 0.0;\n"
        "}\n"
        if standby
        else ""
    )
    output = (
        sig.read(0, "fbk")
        + "/* Voltage reference in stationary coordinates, its angle advanced by\n"
        f" * k_comp*T_s*w_c (k_comp = {K_COMP} of the controller) */\n"
        + f"double complex u_c_ref_ab = cexp(I * fbk.theta_c) * {complex_in(1)};\n"
        + f"u_c_ref_ab *= cexp(I * {K_COMP} * T_s * fbk.w_c);\n"
        + zero_vector
        + complex_out(0, "u_c_ref_ab")
        + "OutputSignal(1, 0) = fbk.w_c;\n"
    )
    m_zero_vector = (
        "% The zero vector of a sensorless drive in standby\n"
        "if p.sensorless > 0 && standby ~= 0\n"
        "    u_c_ref_ab = complex(0);\n"
        "end\n"
        if standby
        else ""
    )
    params = ["T_s", "sensorless"] if standby else ["T_s"]
    mcode = MCode(
        output="% Voltage reference in stationary coordinates, its angle advanced by\n"
        f"% k_comp*T_s*w_c (k_comp = {K_COMP} of the controller)\n"
        f"u_c_ref_ab = exp(1i*fbk.theta_c)*{u};\n"
        f"u_c_ref_ab = u_c_ref_ab*exp(1i*{K_COMP}*p.T_s*fbk.w_c);\n"
        + m_zero_vector
        + "w = fbk.w_c;\n",
        inputs={"fbk": sig.vector("fbk"), u: COMPLEX},
        outputs={"u_c_ref_ab": COMPLEX},
        checks=required(*params),
    )
    start = "T_s = P(0, 0);\n" + ("sensorless = (int)P(1, 0);\n" if standby else "")
    workspace = SAMPLING + ("static int sensorless;\n" if standby else "")
    return CBlock(
        "modulate",
        [sig.port("fbk"), Port(u, 2), *([Port("standby", 1)] if standby else [])],
        [Port("u_c_ref_ab", 2), Port("w", 1)],
        sig.function_code(output, start, workspace),
        params,
        sig.sfunction("modulate"),
        mcode=mcode,
    )


def monitor(
    sig: Signals,
    outputs: dict[str, list[str]],
    monitored: dict[str, str],
    inputs: list[Port],
    prelude: str = "",
) -> CBlock:
    """
    Monitored signals: the groups `outputs` of the expressions `monitored` of the
    feedback signals fbk, the references ref, and the other `inputs`.
    """
    code = sig.function_code(
        sig.read(0, "fbk")
        + sig.read(1, "ref")
        + monitored_code(outputs, monitored, prelude=prelude, first=0)
    )
    ports = [sig.port("fbk"), sig.port("ref"), *inputs]
    m_output = "% Monitored signals\n" + c_to_matlab(prelude, ports)
    for name, signals in outputs.items():
        values = [c_to_matlab(monitored[n], ports) for n in signals]
        line = f"{m_variable(name)} = [{'; '.join(values)}];\n"
        if len(line) > 84:  # One value per line
            line = f"{m_variable(name)} = [ ...\n    " + ";\n    ".join(values) + "];\n"
        m_output += line
    mcode = MCode(
        output=m_output, inputs={"fbk": sig.vector("fbk"), "ref": sig.vector("ref")}
    )
    return CBlock(
        MONITOR,
        ports,
        [Port(name, len(signals)) for name, signals in outputs.items()],
        code,
        ["T_s"],
        sig.sfunction("monitored_signals"),
        mcode=mcode,
    )


