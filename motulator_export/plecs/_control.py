def grid_converter_control_system(
    sig: Signals,
    name: str,
    inputs: list[Port],
    measurement: CBlock,
    inner_ctrl: Subsystem,
    signals: CBlock,
) -> Subsystem:
    """
    Control system of a grid converter (GridConverterControlSystem): the contents of
    the masked subsystem of the control system, whose mask has the sampling period
    T_s.

    The inputs are `enable`, the two references, and the inputs of the measurements.
    The inner controller has the inputs `enable`, the references, `meas`, `u_c_ab`,
    and optionally `u_c_zoh_ab`, and the outputs `fbk` and `ref`. The inputs of the
    monitored signals are `enable`, `fbk`, and `ref`.

    """
    ic = inner_ctrl.name
    zoh = "u_c_zoh_ab" in [p.name for p in inner_ctrl.inputs]
    refs = [p.name for p in inputs[1:3]]
    fbk, ref = sig.width("fbk"), sig.width("ref")
    # The feedback signals and the references to the monitored signals by tags
    tags = [
        Tag("Goto fbk", "fbk", fbk, goto=True),
        Tag("Goto ref", "ref", ref, goto=True),
        Tag("From fbk", "fbk", fbk, goto=False),
        Tag("From ref", "ref", ref, goto=False),
    ]
    return Subsystem(
        name,
        inputs,
        [Port("d_abc", 3)],
        [
            measurement,
            pwm(sig, ("meas.u_g_ab", "meas.u_g_ab")),
            inner_ctrl,
            *tags,
            sig.selector("ref", "u_c", complex_=True),
            modulate(sig, "u_c"),
            signals,
        ],
        [
            (ENABLE, "PWM:enable"),
            (ENABLE, f"{ic}:enable"),
            *((r, f"{ic}:{r}") for r in refs),
            *((p.name, f"get_measurement:{p.name}") for p in measurement.inputs),
            ("get_measurement:meas", "PWM:meas"),
            ("get_measurement:meas", f"{ic}:meas"),
            ("PWM:u_c_ab", f"{ic}:u_c_ab"),
            *([("PWM:u_c_zoh_ab", f"{ic}:u_c_zoh_ab")] if zoh else []),
            ("PWM:d_abc", "d_abc"),
            (f"{ic}:fbk", "Goto fbk"),
            (f"{ic}:fbk", "modulate:fbk"),
            (f"{ic}:ref", "Goto ref"),
            (f"{ic}:ref", "ref.u_c:u"),
            ("ref.u_c:y", "modulate:u_c"),
            ("modulate:u_c_ref_ab", "PWM:u_c_ref_ab"),
            ("modulate:w", "PWM:w"),
            ("From fbk", f"{MONITOR}:fbk"),
            ("From ref", f"{MONITOR}:ref"),
        ],
        columns=[
            [p.name for p in inputs],
            ["get_measurement"],
            ["PWM"],
            [ic, "d_abc"],
            ["Goto fbk", "ref.u_c", "Goto ref", "From fbk", "From ref"],
            ["modulate", MONITOR],
        ],
        align={
            refs[0]: f"{ic}:{refs[0]}-1",
            refs[1]: f"{ic}:{refs[1]}",
            "get_measurement:meas": f"{ic}:meas+1",
            "PWM:meas": "get_measurement:meas+2",
            "d_abc": "PWM:d_abc",
            "modulate:fbk": f"{ic}:fbk",
            "ref.u_c:y": "modulate:u_c+1",
            "Goto fbk": f"{ic}:fbk-1",
            "Goto ref": "ref.u_c:u+1",
            f"{MONITOR}:fbk": "From fbk",
        },
        lanes={"PWM:u_c_ref_ab": "below:1", "PWM:w": "below:0"},
        tags=[ENABLE],
    )


def vhz_control_system(
    sig: Signals,
    name: str,
    inputs: list[Port],
    measurement: CBlock,
    vhz_ctrl: Subsystem,
    signals: CBlock,
) -> Subsystem:
    """
    V/Hz control system of a drive (VHzControlSystem): the contents of the masked
    subsystem of the control system, whose mask has the sampling period T_s.

    The inputs are `enable`, the speed reference `w_M_ref`, and the inputs of the
    measurements. The speed reference is limited by the rate limiter. The V/Hz
    controller has the inputs `enable`, the rate-limited speed reference `w_M`,
    `meas`, `u_c_ab`, and optionally `u_c_zoh_ab`, and the outputs `fbk` and `ref`.
    The inputs of the monitored signals are `enable`, `fbk`, `ref`, and `w_M_ref`
    (the rate-limited speed reference).

    """
    vc = vhz_ctrl.name
    zoh = "u_c_zoh_ab" in [p.name for p in vhz_ctrl.inputs]
    fbk, ref = sig.width("fbk"), sig.width("ref")
    # The feedback signals, the references, and the rate-limited speed reference to
    # the monitored signals by tags
    tags = [
        Tag("Goto w_M", "w_M", 1, goto=True),
        Tag("Goto fbk", "fbk", fbk, goto=True),
        Tag("Goto ref", "ref", ref, goto=True),
        Tag("From fbk", "fbk", fbk, goto=False),
        Tag("From ref", "ref", ref, goto=False),
        Tag("From w_M", "w_M", 1, goto=False),
    ]
    return Subsystem(
        name,
        inputs,
        [Port("d_abc", 3)],
        [
            measurement,
            rate_limiter(sig),
            pwm(sig),
            vhz_ctrl,
            *tags,
            sig.selector("ref", "u_s", complex_=True),
            modulate(sig, "u_s"),
            signals,
        ],
        [
            (ENABLE, "PWM:enable"),
            (ENABLE, f"{vc}:enable"),
            ("w_M_ref", "RateLimiter:u"),
            ("RateLimiter:y", f"{vc}:w_M"),
            ("RateLimiter:y", "Goto w_M"),
            *((p.name, f"get_measurement:{p.name}") for p in measurement.inputs),
            ("get_measurement:meas", "PWM:meas"),
            ("get_measurement:meas", f"{vc}:meas"),
            ("PWM:u_c_ab", f"{vc}:u_c_ab"),
            *([("PWM:u_c_zoh_ab", f"{vc}:u_c_zoh_ab")] if zoh else []),
            ("PWM:d_abc", "d_abc"),
            (f"{vc}:fbk", "Goto fbk"),
            (f"{vc}:fbk", "modulate:fbk"),
            (f"{vc}:ref", "Goto ref"),
            (f"{vc}:ref", "ref.u_s:u"),
            ("ref.u_s:y", "modulate:u_s"),
            ("modulate:u_c_ref_ab", "PWM:u_c_ref_ab"),
            ("modulate:w", "PWM:w"),
            ("From fbk", f"{MONITOR}:fbk"),
            ("From ref", f"{MONITOR}:ref"),
            ("From w_M", f"{MONITOR}:w_M_ref"),
        ],
        columns=[
            [p.name for p in inputs],
            ["RateLimiter", "get_measurement"],
            ["Goto w_M", "PWM"],
            [vc, "d_abc"],
            ["Goto fbk", "ref.u_s", "Goto ref", "From fbk", "From ref", "From w_M"],
            ["modulate", MONITOR],
        ],
        align={
            "RateLimiter:y": f"{vc}:w_M",
            "w_M_ref": "RateLimiter:u",
            "Goto w_M": "RateLimiter:y-1",
            "get_measurement:meas": f"{vc}:meas+1",
            "PWM:meas": "get_measurement:meas+2",
            "d_abc": "PWM:d_abc",
            "modulate:fbk": f"{vc}:fbk",
            "ref.u_s:y": "modulate:u_s+1",
            "Goto fbk": f"{vc}:fbk-1",
            "Goto ref": "ref.u_s:u+1",
            f"{MONITOR}:fbk": "From fbk",
        },
        lanes={"PWM:u_c_ref_ab": "below:1", "PWM:w": "below:0"},
        tags=[ENABLE],
    )


