# C code helpers
def _read(port: int, width: str, var: str) -> str:
    """C code reading an input into an array."""
    return (
        f"double {var}[{width}];\n"
        f"for (int k = 0; k < {width}; k++) {{\n"
        f"    {var}[k] = InputSignal({port}, k);\n"
        "}\n"
    )


def _write(port: int, width: str, var: str) -> str:
    """C code writing an array to an output."""
    return (
        f"for (int k = 0; k < {width}; k++) {{\n"
        f"    OutputSignal({port}, k) = {var}[k];\n"
        "}\n"
    )


def complex_in(port: int) -> str:
    """Complex input."""
    return f"complex_from(InputSignal({port}, 0), InputSignal({port}, 1))"


def complex_out(port: int, value: str) -> str:
    """C code writing a complex variable to an output."""
    return (
        f"OutputSignal({port}, 0) = creal({value});\n"
        f"OutputSignal({port}, 1) = cimag({value});\n"
    )


def checks(params: list[str], scalars: list[str]) -> str:
    """C code checking that the required parameters are scalars."""
    return "".join(
        f"if (PDIM({params.index(p)}) != 1) {{\n"
        f'    SetErrorMessage("{p} must be a scalar.");\n'
        "    return;\n"
        "}\n"
        for p in scalars
    )


def c_to_matlab(code: str, inputs: list[Port]) -> str:
    """
    MATLAB code of the C expressions and declarations of the measurements and the
    monitored signals: the functions of complex.h and the inputs InputSignal(k, j)
    (named by the ports) translated, the types of the declarations removed, and the
    comments converted.
    """
    names = {
        "cabs": "abs",
        "creal": "real",
        "cimag": "imag",
        "carg": "angle",
        "cexp": "exp",
        "fmax": "max",
        "fmin": "min",
    }

    def signal(m: re.Match[str]) -> str:
        port = inputs[int(m[1])]
        return port.name if port.width == 1 else f"{port.name}({int(m[2]) + 1})"

    out = re.sub(r"InputSignal\((\d+), (\d+)\)", signal, code)
    out = re.sub(r"\b(" + "|".join(names) + r")\(", lambda m: names[m[1]] + "(", out)
    out = re.sub(r"\bI \* ", "1i*", out)
    out = re.sub(r"\bU_DC_MIN\b", "1", out)
    out = re.sub(r"^double (complex )?", "", out, flags=re.M)
    out = re.sub(r"/\* (.*?) \*/", r"% \1", out)
    if re.search(r"InputSignal|\bdouble\b|/\*|\bI\b", out):
        raise ValueError(f"Cannot translate the C code: {code}")
    return out


def mask_params(mask: Mask, expanded: dict[str, list[str]] | None = None) -> list[str]:
    """
    Parameters of a C block from its mask: the mask variables, those in `expanded`
    (e.g., the machine model par) replaced by the variables of the mask
    initialization (e.g., its fields), at the end.
    """
    expanded = expanded or {}
    names = [p.variable for p in mask.params if p.variable not in expanded]
    return names + [n for p in mask.params for n in expanded.get(p.variable, [])]


@dataclass(frozen=True)
class Signals:
    """
    C port of a control method for its blocks: the included C files, the headers
    defining the signal vectors (e.g., MEAS_WIDTH and MEAS_u_dc of the measurements
    meas), the C types and the function prefixes of the vectors (e.g., Measurements
    and measurements for measurements_pack and measurements_unpack, and optionally
    the prefix of the macros, by default the name of the vector in upper case), and
    the prefix of the names of the S-functions.
    """

    sources: tuple[str, ...]  # C files, e.g., ("common.c", "sm_flux_vector.c")
    headers: tuple[str, ...]  # e.g., ("sm_flux_vector.h",)
    vectors: dict[str, tuple[str, ...]]  # Vector -> (C type, function prefix[, macro])
    prefix: str  # e.g., "sfun_fvc"

    def macro(self, vector: str) -> str:
        """Prefix of the macros of a signal vector, e.g., "MEAS"."""
        v = self.vectors[vector]
        return v[2] if len(v) > 2 else vector.upper()

    def _define(self, name: str) -> int:
        """Value of a macro of the signal vectors."""
        for header in self.headers:
            try:
                return c_define(header, name)
            except RuntimeError:
                pass
        raise RuntimeError(f"{name} not found in {self.headers}")

    def width(self, vector: str) -> int:
        """Width of a signal vector, e.g., "meas"."""
        return self._define(f"{self.macro(vector)}_WIDTH")

    def index(self, vector: str, name: str) -> int:
        """Index of a field of a signal vector."""
        return self._define(f"{self.macro(vector)}_{name}")

    def port(self, vector: str) -> Port:
        """Port of a signal vector."""
        return Port(vector, self.width(vector))

    def vector(self, vector: str) -> SignalVector:
        """Signal vector in the MATLAB code, its fields from the C header."""
        macro = self.macro(vector)
        found = []
        for header in self.headers:
            text = (C_SOURCES / header).read_text()
            found = re.findall(rf"^#define {macro}_(\w+) (\d+)$", text, re.M)
            if found:
                break
        indices = sorted((int(k), n) for n, k in found if n != "WIDTH")
        ends = [k for k, _ in indices[1:]] + [self.width(vector)]
        fields = tuple((n, end - k) for (k, n), end in zip(indices, ends, strict=True))
        return SignalVector(self.vectors[vector][1], fields)

    def selector(self, vector: str, name: str, complex_: bool = False) -> Selector:
        """Selector of a field of a signal vector, e.g., "fbk.w_M"."""
        k = self.index(vector, name)
        indices = [k, k + 1] if complex_ else [k]
        return Selector(f"{vector}.{name}", self.width(vector), indices)

    def read(self, port: int, vector: str, declare: bool = True) -> str:
        """C code reading a signal vector from an input into the variable `vector`."""
        typ, fn = self.vectors[vector][:2]
        width = f"{self.macro(vector)}_WIDTH"
        return (
            _read(port, width, f"{vector}_u")
            + (f"{typ} {vector};\n" if declare else "")
            + f"{fn}_unpack({vector}_u, &{vector});\n"
        )

    def write(self, port: int, vector: str, var: str) -> str:
        """C code writing the variable `var` as a signal vector to an output."""
        width = f"{self.macro(vector)}_WIDTH"
        return (
            f"double y[{width}];\n"
            f"{self.vectors[vector][1]}_pack(&{var}, y);\n" + _write(port, width, "y")
        )

    def sfunction(self, name: str) -> str:
        """Name of the S-function of a block."""
        return f"{self.prefix}_{name}"

    def declarations(self, workspace: str = "") -> str:
        """Declarations of the C code of a block."""
        includes = "".join(f'#include "{C_DIR}/{f}"\n' for f in self.sources)
        gradnet = "\n" + C_GRADNET_PARAMS if "gradnet.c" in self.sources else ""
        return HEADER + includes + "\n" + C_PARAMS + gradnet + "\n" + workspace

    def class_code(
        self, cls: str, start: str, output: str, update: str = "", workspace: str = ""
    ) -> dict[str, str]:
        """
        Code sections of the block of a class: its state `self` of the type `cls` is
        initialized by `start` from the parameters, which are read only there (the
        parameters used later are copied to the `workspace` variables).
        """
        return {
            "Declarations": self.declarations(f"static {cls} self;\n" + workspace),
            "StartFcn": start,
            "OutputFcn": output,
            "UpdateFcn": update,
        }

    def function_code(
        self, output: str, start: str = "", workspace: str = ""
    ) -> dict[str, str]:
        """Code sections of the block of a function (without a state)."""
        return {
            "Declarations": self.declarations(workspace),
            "StartFcn": start,
            "OutputFcn": output,
        }


