def vector_control_system(
    sig: Signals,
    name: str,
    inputs: list[Port],
    measurement: CBlock,
    vector_ctrl: Subsystem,
    signals: CBlock,
) -> Subsystem:
    """
    Vector control system of a drive (VectorControlSystem): the contents of the
    masked subsystem of the control system, whose mask has the sampling period T_s.

    The vector controller has the inputs `enable`, `tau_M_ref`, `meas`, `u_c_ab`,
    and optionally `u_c_zoh_ab`, and the outputs `fbk` and `ref`. The inputs of the
    monitored signals are `enable`, `fbk`, `ref`, and `w_M_ref`.

    """
    vc = vector_ctrl.name
    zoh = "u_c_zoh_ab" in [p.name for p in vector_ctrl.inputs]
    fbk, ref = sig.width("fbk"), sig.width("ref")
    # The feedback signals and the references to the speed controller and to the
    # monitored signals by tags, the others by wires
    tags = [
        Tag("Goto fbk", "fbk", fbk, goto=True),
        Tag("Goto ref", "ref", ref, goto=True),
        Tag("From fbk", "fbk", fbk, goto=False),
        Tag("From ref", "ref", ref, goto=False),
        Tag("From fbk 2", "fbk", fbk, goto=False),
        Tag("From ref 2", "ref", ref, goto=False),
    ]
    meas = [(p.name, f"get_measurement:{p.name}") for p in measurement.inputs]
    return Subsystem(
        name,
        inputs,
        [Port("d_abc", 3)],
        [
            measurement,
            *tags,
            sig.selector("fbk", "w_M"),
            sig.selector("ref", "tau_M"),
            speed_controller(sig),
            pwm(sig),
            vector_ctrl,
            sig.selector("ref", "u_s", complex_=True),
            modulate(sig, "u_s"),
            signals,
        ],
        [
            (ENABLE, "SpeedController:enable"),
            (ENABLE, "PWM:enable"),
            (ENABLE, f"{vc}:enable"),
            (ENABLE, f"{MONITOR}:enable"),
            ("w_M_ref", "SpeedController:w_M_ref"),
            ("w_M_ref", f"{MONITOR}:w_M_ref"),
            *meas,
            ("get_measurement:meas", "PWM:meas"),
            ("get_measurement:meas", f"{vc}:meas"),
            ("From fbk", "fbk.w_M:u"),
            ("From ref", "ref.tau_M:u"),
            ("fbk.w_M:y", "SpeedController:w_M"),
            ("ref.tau_M:y", "SpeedController:tau_M"),
            ("SpeedController:tau_M_ref", f"{vc}:tau_M_ref"),
            ("PWM:u_c_ab", f"{vc}:u_c_ab"),
            *([("PWM:u_c_zoh_ab", f"{vc}:u_c_zoh_ab")] if zoh else []),
            ("PWM:d_abc", "d_abc"),
            (f"{vc}:fbk", "Goto fbk"),
            (f"{vc}:fbk", "modulate:fbk"),
            (f"{vc}:ref", "Goto ref"),
            (f"{vc}:ref", "ref.u_s:u"),
            ("ref.u_s:y", "modulate:u_s"),
            ("modulate:u_c_ref_ab", "PWM:u_c_ref_ab"),
            ("modulate:w", "PWM:w"),
            ("From fbk 2", f"{MONITOR}:fbk"),
            ("From ref 2", f"{MONITOR}:ref"),
        ],
        columns=[
            [p.name for p in inputs],
            ["From fbk", "From ref", "get_measurement"],
            ["fbk.w_M", "ref.tau_M"],
            ["SpeedController", "PWM"],
            [vc, "d_abc"],
            ["Goto fbk", "ref.u_s", "Goto ref", "From fbk 2", "From ref 2"],
            ["modulate", MONITOR],
        ],
        align={
            "fbk.w_M:u": "From fbk",
            "ref.tau_M:u": "From ref",
            "SpeedController:w_M": "fbk.w_M:y",
            "get_measurement:meas": "SpeedController:tau_M_ref+1",
            "PWM:meas": "get_measurement:meas+2",
            f"{vc}:meas": "get_measurement:meas",
            "d_abc": "PWM:d_abc",
            "modulate:fbk": f"{vc}:fbk",
            "ref.u_s:y": "modulate:u_s+1",
            "Goto fbk": f"{vc}:fbk-1",
            "Goto ref": "ref.u_s:u+1",
            f"{MONITOR}:fbk": "From fbk 2",
        },
        lanes={"PWM:u_c_ref_ab": "below:1", "PWM:w": "below:0"},
        tags=[ENABLE, "w_M_ref"],
    )


def grid_converter_control_system(
    sig: Signals,
    name: str,
    inputs: list[Port],
    measurement: CBlock,
    inner_ctrl: Subsystem,
    signals: CBlock,
) -> Subsystem:
    """
    Control system of a grid converter (GridConverterControlSystem): the contents of
    the masked subsystem of the control system, whose mask has the sampling period
    T_s.

    The inputs are `enable`, the two references, and the inputs of the measurements.
    The inner controller has the inputs `enable`, the references, `meas`, and
    `u_c_ab`, and the outputs `fbk` and `ref`. The inputs of the monitored signals
    are `enable`, `fbk`, and `ref`.

    """
    ic = inner_ctrl.name
    refs = [p.name for p in inputs[1:3]]
    fbk, ref = sig.width("fbk"), sig.width("ref")
    # The feedback signals and the references to the monitored signals by tags
    tags = [
        Tag("Goto fbk", "fbk", fbk, goto=True),
        Tag("Goto ref", "ref", ref, goto=True),
        Tag("From fbk", "fbk", fbk, goto=False),
        Tag("From ref", "ref", ref, goto=False),
    ]
    return Subsystem(
        name,
        inputs,
        [Port("d_abc", 3)],
        [
            measurement,
            pwm(sig),
            inner_ctrl,
            *tags,
            sig.selector("ref", "u_c", complex_=True),
            modulate(sig, "u_c"),
            signals,
        ],
        [
            (ENABLE, "PWM:enable"),
            (ENABLE, f"{ic}:enable"),
            (ENABLE, f"{MONITOR}:enable"),
            *((r, f"{ic}:{r}") for r in refs),
            *((p.name, f"get_measurement:{p.name}") for p in measurement.inputs),
            ("get_measurement:meas", "PWM:meas"),
            ("get_measurement:meas", f"{ic}:meas"),
            ("PWM:u_c_ab", f"{ic}:u_c_ab"),
            ("PWM:d_abc", "d_abc"),
            (f"{ic}:fbk", "Goto fbk"),
            (f"{ic}:fbk", "modulate:fbk"),
            (f"{ic}:ref", "Goto ref"),
            (f"{ic}:ref", "ref.u_c:u"),
            ("ref.u_c:y", "modulate:u_c"),
            ("modulate:u_c_ref_ab", "PWM:u_c_ref_ab"),
            ("modulate:w", "PWM:w"),
            ("From fbk", f"{MONITOR}:fbk"),
            ("From ref", f"{MONITOR}:ref"),
        ],
        columns=[
            [p.name for p in inputs],
            ["get_measurement"],
            ["PWM"],
            [ic, "d_abc"],
            ["Goto fbk", "ref.u_c", "Goto ref", "From fbk", "From ref"],
            ["modulate", MONITOR],
        ],
        align={
            refs[0]: f"{ic}:{refs[0]}-1",
            refs[1]: f"{ic}:{refs[1]}",
            "get_measurement:meas": f"{ic}:meas+1",
            "PWM:meas": "get_measurement:meas+2",
            "d_abc": "PWM:d_abc",
            "modulate:fbk": f"{ic}:fbk",
            "ref.u_c:y": "modulate:u_c+1",
            "Goto fbk": f"{ic}:fbk-1",
            "Goto ref": "ref.u_c:u+1",
            f"{MONITOR}:fbk": "From fbk",
        },
        lanes={"PWM:u_c_ref_ab": "below:1", "PWM:w": "below:0"},
        tags=[ENABLE],
    )


