"""
Export grid converter systems to Simulink.

This module writes a Simulink model of a motulator grid converter system with
grid-following or grid-forming control, in the same way as
`motulator_export.plecs._grid` writes a PLECS model. The blocks of the classes of
the control system are the C-Script code of the PLECS model wrapped in S-functions,
or MATLAB Function blocks running the MATLAB port of motulator (`code`), and the
parameters are defined by the script `init_<model>.m` (see
`motulator_export.simulink._sm`). The system model is built from basic Simulink
blocks by `build_grid.m`: the AC filter (an LCL filter, or an L filter with the grid
inductance) is modeled with space vectors in stationary coordinates, and the grid
voltage is generated by Sine Wave blocks.

Currently supported: the grid converter systems and control systems of
`motulator_export.plecs._grid`.

"""

from pathlib import Path
from typing import Any, cast

import numpy as np
from motulator.grid.control import GridConverterControlSystem
from motulator.grid.model import GridConverterSystem, LCLFilter

from motulator_export.plecs import _grid, _grid_control
from motulator_export.plecs._common import StepSignal
from motulator_export.plecs._control import VALUES
from motulator_export.simulink._common import (
    _m_source,
    check_supported_model,
    scope_indices,
    write_init,
    write_script,
)
from motulator_export.simulink._common import simulate as _simulate


def _plant_variables(mdl: GridConverterSystem) -> list[tuple[str, Any]]:
    """Workspace variables of the system model, see `_grid._plant_variables`."""
    # The initial capacitor voltage as a space vector [real imag]
    variables = []
    for name, value in _grid._plant_variables(mdl):
        if name == "ac_filter.u_f0_abc":
            u_f0_ab = cast(LCLFilter, mdl.ac_filter).state.u_f_ab
            variables.append(("ac_filter.u_f0_ab", [u_f0_ab.real, u_f0_ab.imag]))
        else:
            variables.append((name, value))
    return variables


def write_model(
    path: str | Path,
    mdl: GridConverterSystem,
    ctrl: GridConverterControlSystem,
    t_stop: float,
    code: str = "c",
) -> Path:
    """
    Write the MATLAB scripts that build the Simulink model of the grid converter
    system, see `simulink.write_model` and `plecs._grid.write_model`.
    """
    path = Path(path)
    _grid._check_supported(mdl, ctrl)
    check_supported_model(mdl, ctrl)
    block, values = _grid.control_block(ctrl), _grid.export_values(ctrl)
    # The references are checked before anything is written
    references = _grid.grid_references(ctrl, block is _grid.GFL_BLOCK, values["T_s"])
    variables = _plant_variables(mdl)
    script = write_init(
        path,
        lambda comment: _grid_control.init_script(
            variables, values, comment, gfl=block is _grid.GFL_BLOCK
        ),
    )
    refs: list[list[Any]] = [["enable", "constant", 1.0]]  # The gates are not blocked
    for name, ref in references:
        kind = "step" if isinstance(ref, StepSignal) else "constant"
        refs.append([name, kind, _m_source(ref)])
    # Scope: the powers, the converter currents, and the other monitored signals
    groups = list(block.outputs.items())
    scope = [("Power", [f"ctrl.{n}" for n in groups[0][1]])]
    scope += [("Converter current", ["mdl.i_c_a", "mdl.i_c_b", "mdl.i_c_c"])]
    scope += [(name.split(" (")[0], [f"ctrl.{n}" for n in s]) for name, s in groups[1:]]
    fields = [
        ("init_script", script),
        ("ac_filter", "lcl" if isinstance(mdl.ac_filter, LCLFilter) else "l"),
        ("refs", refs),
        ("scope", scope_indices(scope, _grid._mdl_outputs(mdl), block.signals)),
    ]
    return write_script(
        path, block, VALUES, fields, "build_grid", VALUES["T_s"], t_stop, code=code
    )


def simulate(
    path: str | Path,
    t_eval: np.ndarray,
    mdl: GridConverterSystem,
    ctrl: GridConverterControlSystem,
    build: bool = True,
) -> tuple[dict[str, np.ndarray], dict[str, np.ndarray]]:
    """
    Simulate the Simulink model of a grid converter system, see `simulink.simulate`.
    """
    signals = _grid.control_block(ctrl).signals
    return _simulate(path, t_eval, _grid._mdl_outputs(mdl), signals, build)
