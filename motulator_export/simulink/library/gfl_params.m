function ctrl_par = gfl_params(inner_ctrl, pwm)
%GFL_PARAMS Parameters of the blocks of the control system
%   Grid-following control.
%   CTRL_PAR = GFL_PARAMS(INNER_CTRL, PWM) gives the struct CTRL_PAR with a struct
%   of the parameters for each block of the control system, nested as the blocks,
%   and the sampling period T_s, from the arguments of the top-level class of
%   motulator as structs (see the method params of the MATLAB classes of motulator).
%   The MATLAB Function blocks of the control system refer to the variable ctrl_par
%   of the model, e.g., to ctrl_par.PWM.compute_output. An empty parameter ([], None
%   in motulator) is NaN in the structs of the blocks. The initialization script of
%   a model calls this function, copied into the folder of the model. Generated by
%   motulator_export from the masks of the blocks of the control system.
T_s = inner_ctrl.cfg.T_s;
ctrl_par = struct();
% Sampling period
ctrl_par.T_s = T_s;
p = struct();
p.T_s = T_s;
p = numeric_fields(p);
ctrl_par.get_measurement = p;
ctrl_par.PWM = PWM(T_s, pwm.t_d, pwm.u_th, pwm.i_0, pwm.feedforward, pwm.d_min, ...
    pwm.single_update, pwm.overmodulation);
ctrl_par.CurrentVectorController = CurrentVectorController(inner_ctrl.cfg);
p = struct();
p.T_s = T_s;
p = numeric_fields(p);
if ~isscalar(p.T_s) || isnan(p.T_s)
    error('modulate: T_s must be a scalar.');
end
ctrl_par.modulate = p;
p = struct();
p.T_s = T_s;
p = numeric_fields(p);
ctrl_par.Monitored_signals = p;
end

