function s = CurrentVectorController(cfg)
%CURRENTVECTORCONTROLLER Parameters of the block CurrentVectorController
%   (CurrentVectorController of motulator) from the arguments of its class.
s = struct();
s.PLL = CurrentVectorController_PLL(cfg.u_nom, cfg.w_nom, cfg.alpha_pll, ...
    cfg.T_s);
p = struct();
p.T_s = cfg.T_s;
p = numeric_fields(p);
if ~isscalar(p.T_s) || isnan(p.T_s)
    error('compute_output: T_s must be a scalar.');
end
s.compute_output = p;
s.CurrentLimiter = CurrentVectorController_CurrentLimiter(cfg.i_max);
p = struct();
p.T_s = cfg.T_s;
p = numeric_fields(p);
if ~isscalar(p.T_s) || isnan(p.T_s)
    error('power_reference: T_s must be a scalar.');
end
s.power_reference = p;
p = struct();
p = numeric_fields(p);
s.compute_standby_output = p;
s.CurrentController = CurrentVectorController_CurrentController(cfg.L, ...
    cfg.alpha_c, cfg.alpha_i, cfg.T_s);
end

