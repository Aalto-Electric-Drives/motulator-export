function p = numeric_fields(p)
%NUMERIC_FIELDS Fields of the struct p as doubles, [] (None) as NaN.
names = fieldnames(p);
for k = 1:numel(names)
    if isempty(p.(names{k}))
        p.(names{k}) = NaN;
    else
        p.(names{k}) = double(p.(names{k}));
    end
end
