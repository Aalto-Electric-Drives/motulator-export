function s = ObserverBasedGridFormingController(cfg)
%OBSERVERBASEDGRIDFORMINGCONTROLLER Parameters of the block
%   ObserverBasedGridFormingController (ObserverBasedGridFormingController of
%   motulator) from the arguments of its class.
% Defaults of R_a and k_v (ObserverBasedGridFormingController.__init__)
R_a = cfg.R_a;
if isempty(R_a)
    R_a = 0.25*cfg.u_nom/cfg.i_max;
end
k_v = cfg.k_v;
if isempty(k_v)
    k_v = cfg.alpha_o/cfg.w_nom;
end
% Current-control gain (ObserverBasedGridFormingController.__init__)
k_c = cfg.alpha_c*cfg.L;
% Other parameters of compute_output
R = cfg.R;
% PowerReferenceLimiter (none without i_d_max)
i_d_max = cfg.i_d_max;
alpha_l = cfg.alpha_l;
u_nom = cfg.u_nom;
T_s = cfg.T_s;
s = struct();
s.Observer = ObserverBasedGridFormingController_Observer(cfg.u_nom, cfg.w_nom, ...
    cfg.L, cfg.alpha_o, cfg.T_s, cfg.R);
s.PowerReferenceLimiter = ...
    ObserverBasedGridFormingController_PowerReferenceLimiter(i_d_max, alpha_l, ...
    u_nom, T_s);
p = struct();
p.R_a = R_a;
p.k_v = k_v;
p.k_c = k_c;
p = numeric_fields(p);
if ~isscalar(p.R_a) || isnan(p.R_a)
    error('compute_output: R_a must be a scalar.');
end
if ~isscalar(p.k_v) || isnan(p.k_v)
    error('compute_output: k_v must be a scalar.');
end
if ~isscalar(p.k_c) || isnan(p.k_c)
    error('compute_output: k_c must be a scalar.');
end
s.compute_output = p;
s.CurrentLimiter = ObserverBasedGridFormingController_CurrentLimiter(cfg.i_max);
p = struct();
p = numeric_fields(p);
s.compute_standby_output = p;
p = struct();
p.k_c = k_c;
p.R = R;
p = numeric_fields(p);
if ~isscalar(p.k_c) || isnan(p.k_c)
    error('voltage_reference: k_c must be a scalar.');
end
if ~isscalar(p.R) || isnan(p.R)
    error('voltage_reference: R must be a scalar.');
end
s.voltage_reference = p;
end

