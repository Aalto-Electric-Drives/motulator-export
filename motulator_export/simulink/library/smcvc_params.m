    gn_activation = par.psi_s_dq_fcn.activation;
    gn_beta_log = par.psi_s_dq_fcn.beta_log;
    gn_p = par.psi_s_dq_fcn.p;
    gn_in_base = par.psi_s_dq_fcn.in_base;
    gn_out_base = par.psi_s_dq_fcn.out_base;
else
    par_L_d = par.L_d;
    par_L_q = par.L_q;
    par_psi_f = par.psi_f;
    gn_in_dim = [];
    gn_mu_dim = [];
    gn_W = [];
    gn_b = [];
    gn_mu_log = [];
    gn_bias = [];
    gn_activation = [];
    gn_beta_log = [];
    gn_p = [];
    gn_in_base = [];
    gn_out_base = [];
end
p = struct();
