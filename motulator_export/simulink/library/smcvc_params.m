function s = CurrentVectorController_SpeedFluxObserver(par, alpha_o, k_o, k_f, ...
    sensorless, J, w_M, T_s)
%CURRENTVECTORCONTROLLER_SPEEDFLUXOBSERVER Parameters of the block SpeedFluxObserver
%   (SpeedFluxObserver of motulator) from the arguments of its class.
% Default speed estimation poles of create_speed_flux_observer
% (default_alpha_o). With J, the triple pole at alpha_o/sqrt(3) keeps the
% speed gain about the same.
alpha_o_obs = alpha_o;
if isempty(alpha_o_obs)
    if sensorless
        alpha_o_obs = 2*pi*50;
    else
        alpha_o_obs = 2*pi*400;
    end
    if ~isempty(J)
        alpha_o_obs = alpha_o_obs/sqrt(3);
    end
end
% Default observer gain of create_speed_flux_observer, k_o(w_m) = k0 +
% k1*abs(w_m) (k0 = NaN: sigma0 of the machine model, see the FluxObserver)
k_o_obs = k_o;
if isempty(k_o_obs)
    if sensorless
        k_o_obs = [NaN 0.2];
    else
        k_o_obs = [2*pi*15 0];
    end
end
% Gains for critically damped dynamics (SpeedFluxObserver.__init__), the
% pole matched to the sampling period (matched_pole)
alpha_o_obs = -expm1(-alpha_o_obs*T_s)/T_s;
if isempty(J)
    k_theta = 2*alpha_o_obs;
    k_w = alpha_o_obs^2;
    k_tau = 0;
else
    k_theta = 3*alpha_o_obs;
    k_w = 3*alpha_o_obs^2;
    k_tau = J*alpha_o_obs^3;
end
% Weight of the measured rotor angle in the FluxObserver (position_error)
h = 1 - sensorless;
s = struct();
s.FluxObserver = CurrentVectorController_SpeedFluxObserver_FluxObserver(par, ...
    k_theta, k_o_obs, k_f, h, T_s);
s.SpeedObserver = CurrentVectorController_SpeedFluxObserver_SpeedObserver(k_w, ...
    k_tau, J, w_M, T_s);
end

