p.gn_mu_dim = gn_mu_dim;
p.gn_W = gn_W;
p.gn_b = gn_b;
p.gn_mu_log = gn_mu_log;
p.gn_bias = gn_bias;
p.gn_activation = gn_activation;
p.gn_beta_log = gn_beta_log;
p.gn_p = gn_p;
p.gn_in_base = gn_in_base;
p.gn_out_base = gn_out_base;
